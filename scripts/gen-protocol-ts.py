#!/usr/bin/env python3
"""Write the two index files of the generated protocol types.

ts-rs writes one file for each type in packages/sdk/src/protocol/ (and in
engine/ for the engine protocol). This script writes index.ts in both folders,
so the package can import all of them from one place. Run it after
`cargo test -p sayso-protocol --features ts`; scripts/check-protocol-ts.sh does.

The index has one line for each generated file. A file is generated when its
first line says so. The index files themselves and other files are skipped.
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent / "packages" / "sdk" / "src" / "protocol"
MARK = "This file was generated by [ts-rs]"
HEADER = "// This file was generated by scripts/gen-protocol-ts.py. Do not edit it.\n"


def generated(folder: pathlib.Path, subfolders=()):
    """The (name, path) of each type file that ts-rs wrote in `folder`, and in
    the subfolders that the index also exports (ts-rs puts the types of other
    crates, such as JsonValue, in a folder of their own)."""
    found = []
    for where in (folder, *(folder / sub for sub in subfolders)):
        for path in where.glob("*.ts"):
            if path.name != "index.ts" and MARK in path.read_text().split("\n", 1)[0]:
                found.append((path.stem, path.relative_to(folder).with_suffix(".js").as_posix()))
    return sorted(found)


def write_index(folder: pathlib.Path, subfolders=(), extra: str = "") -> int:
    entries = generated(folder, subfolders)
    lines = [HEADER]
    lines += [f'export type {{ {name} }} from "./{rel}";\n' for name, rel in entries]
    lines.append(extra)
    (folder / "index.ts").write_text("".join(lines))
    return len(entries)


def main() -> int:
    if not (ROOT / "engine").is_dir():
        print(f"{ROOT}/engine is missing. Run: cargo test -p sayso-protocol --features ts", file=sys.stderr)
        return 1
    engine = write_index(ROOT / "engine")
    # The root index also exports the namespace of the engine protocol: it has
    # types with the same names as the Host API (Hello, Request, Reply, ...).
    host = write_index(ROOT, ("serde_json",), 'export * as engine from "./engine/index.js";\n')
    print(f"gen-protocol-ts: {host} host types, {engine} engine types")
    return 0


if __name__ == "__main__":
    sys.exit(main())
